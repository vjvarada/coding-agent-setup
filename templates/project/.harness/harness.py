#!/usr/bin/env python3
"""harness.py — keep this workspace's agent harness honest.

Installed by coding-agent-setup's scaffolder (scaffold/scaffold.py). Stdlib only;
runs anywhere Python >= 3.9 runs. Every agent host reads the same harness:

  AGENTS.md                      the contract (DOX root) every host reads
  .github/skills/<name>/         canonical skills: SKILL.md + scripts/ + tests/
  .claude/skills/<name>/         GENERATED proxies so Claude Code discovers them
  .harness/project.json          what this project is (archetype, stack, hosts)

Commands
  check [--strict]   verify the harness; CI runs this. --strict also fails on
                     unfinished scaffold markers (the scaffolder's final gate).
  sync               regenerate skill proxies and every skills table between
                     <!-- harness:skills:start --> / <!-- harness:skills:end -->
  test               run each skill's tests/ and a --help smoke of its scripts
  session-start      a short status block for the SessionStart hook

Exit codes: 0 ok · 1 problems found · 2 not a scaffolded workspace
"""
from __future__ import annotations

import argparse
import json
import os
import re
import shutil
import subprocess
import sys
from dataclasses import dataclass, field
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

SKILLS_REL = ".github/skills"
GENERATED = "<!-- GENERATED by .harness/harness.py sync — do not edit."
MARK_START = "<!-- harness:skills:start -->"
MARK_END = "<!-- harness:skills:end -->"
# Built in two parts so this file never matches its own scan.
TODO_MARK = "TODO(" + "scaffold)"

NAME_RE = re.compile(r"^[a-z0-9]+(?:-[a-z0-9]+)*$")
AUTHORITIES = ("read", "write", "external")
SKIP_DIRS = {
    ".git", "node_modules", ".venv", "venv", "env", "__pycache__", "dist", "build",
    "target", ".next", ".nuxt", ".turbo", "coverage", "graphify-out", ".pio",
    ".dart_tool", "bin", "obj", ".gradle", ".idea", ".pytest_cache", ".ruff_cache",
    ".mypy_cache", "outputs", "inputs",
}
OS_JUNK = {".DS_Store", "Thumbs.db", "desktop.ini", "ehthumbs.db"}
TEXT_SUFFIXES = {
    ".md", ".json", ".yml", ".yaml", ".py", ".toml", ".txt", ".mjs", ".js", ".cjs",
    ".ts", ".tsx", ".sh", ".ps1", ".cfg", ".ini", ".env.example", ".mdc",
}


# ────────────────────────────────────────────────────────────── utilities ──

def _out(text: str = "") -> None:
    try:
        sys.stdout.write(text + "\n")
    except UnicodeEncodeError:
        sys.stdout.write(text.encode("ascii", "replace").decode("ascii") + "\n")


def load_project(root: Path) -> dict:
    path = root / ".harness" / "project.json"
    if not path.exists():
        return {}
    return json.loads(path.read_text(encoding="utf-8-sig"))


def rel(root: Path, path: Path) -> str:
    return path.relative_to(root).as_posix()


def write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as fh:  # Path.write_text(newline=) is 3.10+
        fh.write(text)


def utf8_env() -> dict:
    """Child Pythons write UTF-8 to our pipes (Windows defaults pipes to cp1252)."""
    return dict(os.environ, PYTHONIOENCODING="utf-8", PYTHONUTF8="1")


def parse_frontmatter(text: str) -> tuple[dict, str]:
    """Minimal YAML front matter: `key: value`, quoted scalars, folded/literal blocks.

    Lists and nested maps are kept as their raw string. That is all a SKILL.md
    header needs, and it keeps this file free of a PyYAML dependency.
    """
    text = text.lstrip("﻿")  # an editor's UTF-8 BOM must not hide the front matter
    if not text.startswith("---"):
        return {}, text
    lines = text.splitlines()
    end = next((i for i, ln in enumerate(lines[1:], 1) if ln.strip() == "---"), None)
    if end is None:
        return {}, text
    meta: dict[str, list[str]] = {}
    key = None
    for raw in lines[1:end]:
        if raw[:1] not in (" ", "\t") and ":" in raw and not raw.lstrip().startswith("#"):
            key, _, value = raw.partition(":")
            key = key.strip()
            value = value.strip()
            meta[key] = [] if value in (">", "|", ">-", "|-", ">+", "|+") else [value]
        elif key and raw.strip():
            meta[key].append(raw.strip())
    parsed = {k: _unquote(" ".join(v).strip()) for k, v in meta.items()}
    return parsed, "\n".join(lines[end + 1:])


def _unquote(value: str) -> str:
    if len(value) >= 2 and value[0] == value[-1] == "'":
        return value[1:-1].replace("''", "'")
    if len(value) >= 2 and value[0] == value[-1] == '"':
        return value[1:-1].replace('\\"', '"')
    return value


def yaml_quote(value: str) -> str:
    return "'" + value.replace("'", "''") + "'"


def walk_files(root: Path):
    """Every file under root, skipping dependency/build/output folders."""
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = [d for d in dirnames if d not in SKIP_DIRS]
        here = Path(dirpath)
        # .tmp/ is scratch except .tmp/scripts/ (DOE shared utilities).
        if here.name == ".tmp":
            dirnames[:] = [d for d in dirnames if d == "scripts"]
            filenames = []
        for name in filenames:
            yield here / name


# ───────────────────────────────────────────────────────────────── skills ──

@dataclass
class Skill:
    name: str
    path: Path
    meta: dict = field(default_factory=dict)
    problems: list = field(default_factory=list)

    @property
    def description(self) -> str:
        return " ".join(self.meta.get("description", "").split())


def discover_skills(root: Path) -> list[Skill]:
    base = root / SKILLS_REL
    if not base.is_dir():
        return []
    skills = []
    for d in sorted(p for p in base.iterdir() if p.is_dir()):
        skill_md = d / "SKILL.md"
        s = Skill(name=d.name, path=d)
        if not skill_md.exists():
            s.problems.append(f"{rel(root, d)}/ has no SKILL.md")
            skills.append(s)
            continue
        s.meta, _ = parse_frontmatter(skill_md.read_text(encoding="utf-8-sig"))
        name = s.meta.get("name", "")
        if not name:
            s.problems.append(f"{rel(root, skill_md)}: front matter has no `name`")
        elif name != d.name:
            s.problems.append(f"{rel(root, skill_md)}: name `{name}` does not match its folder `{d.name}`")
        if not NAME_RE.match(d.name) or len(d.name) > 64:
            s.problems.append(f"{rel(root, d)}: skill names are kebab-case, <= 64 chars")
        desc = s.description
        if not desc:
            s.problems.append(f"{rel(root, skill_md)}: front matter has no `description` (hosts route on it)")
        elif len(desc) > 1024:
            s.problems.append(f"{rel(root, skill_md)}: description is {len(desc)} chars (max 1024)")
        auth = s.meta.get("authority")
        if auth and auth not in AUTHORITIES:
            s.problems.append(f"{rel(root, skill_md)}: authority `{auth}` is not one of {', '.join(AUTHORITIES)}")
        tier = s.meta.get("cost_tier")
        if tier and not (tier.isdigit() and 0 <= int(tier) <= 3):
            s.problems.append(f"{rel(root, skill_md)}: cost_tier `{tier}` must be 0-3")
        skills.append(s)
    return skills


def proxy_text(skill: Skill) -> str:
    canonical = f"{SKILLS_REL}/{skill.name}"
    return (
        "---\n"
        f"name: {skill.name}\n"
        f"description: {yaml_quote(skill.description)}\n"
        "---\n"
        f"{GENERATED} Canonical: {canonical}/SKILL.md -->\n\n"
        f"# {skill.name} (proxy)\n\n"
        "The canonical skill lives in the shared harness, so Claude Code, GitHub Copilot\n"
        "and every other AGENTS.md-aware host run the *same* instructions.\n\n"
        f"**Read `{canonical}/SKILL.md` now and follow it.**\n\n"
        f"- Scripts: `{canonical}/scripts/` — run them from the repo root.\n"
        "- Workspace rules: `AGENTS.md`.\n"
    )


def skills_table(skills: list[Skill]) -> str:
    rows = [
        "| Skill | What it does | Authority |",
        "|---|---|---|",
    ]
    for s in skills:
        if not s.meta:
            continue
        desc = s.description
        first = re.split(r"(?<=[.!?])\s", desc, maxsplit=1)[0] if desc else ""
        if len(first) > 160:
            first = first[:157].rstrip() + "..."
        auth = s.meta.get("authority", "read")
        tier = s.meta.get("cost_tier")
        auth_cell = f"{auth}" + (f" · cost {tier}" if tier else "")
        rows.append(f"| [`{s.name}`]({SKILLS_REL}/{s.name}/SKILL.md) | {first.replace('|', '/')} | {auth_cell} |")
    if len(rows) == 2:
        rows.append("| _(none yet)_ | Create one with the `skill-authoring` skill. | |")
    return "\n".join(rows)


def _marker_files(root: Path) -> list[Path]:
    candidates = [root / "AGENTS.md", root / "CLAUDE.md", root / ".github" / "copilot-instructions.md",
                  root / ".github" / "prompts" / "system.md"]
    agents_dir = root / ".github" / "agents"
    if agents_dir.is_dir():
        candidates += sorted(agents_dir.glob("*.agent.md"))
    return [p for p in candidates if p.exists()]


def _replace_block(text: str, block: str) -> str:
    pattern = re.compile(re.escape(MARK_START) + r".*?" + re.escape(MARK_END), re.S)
    return pattern.sub(lambda _m: f"{MARK_START}\n{block}\n{MARK_END}", text)


def sync(root: Path, check_only: bool = False) -> list[str]:
    """Bring proxies and skills tables in line with .github/skills. Returns drift."""
    project = load_project(root)
    discovered = discover_skills(root)
    canonical = {s.name for s in discovered}
    skills = [s for s in discovered if s.meta.get("name")]
    drift: list[str] = []

    for proxy_dir in project.get("skill_proxy_dirs", [".claude/skills"]):
        base = root / proxy_dir
        wanted = {s.name: proxy_text(s) for s in skills}
        for name, text in wanted.items():
            target = base / name / "SKILL.md"
            current = target.read_text(encoding="utf-8") if target.exists() else None
            if current == text:
                continue
            if current is not None and GENERATED not in current:
                drift.append(f"{rel(root, target)} is hand-written, not a proxy; "
                             f"move its content into {SKILLS_REL}/{name}/ and delete it")
                continue
            drift.append(f"{rel(root, target)} {'missing' if current is None else 'out of date'}")
            if not check_only:
                write(target, text)
        if base.is_dir():
            for d in sorted(p for p in base.iterdir() if p.is_dir()):
                f = d / "SKILL.md"
                # A canonical folder whose SKILL.md fails to parse still owns its proxy:
                # `check` reports the parse problem; deleting the proxy would hide it.
                if d.name in wanted or d.name in canonical or not f.exists():
                    continue
                if GENERATED in f.read_text(encoding="utf-8"):
                    drift.append(f"{rel(root, f)} is an orphan proxy (no canonical skill)")
                    if not check_only:
                        shutil.rmtree(d)

    block = skills_table(skills)
    for path in _marker_files(root):
        text = path.read_text(encoding="utf-8")
        if MARK_START not in text or MARK_END not in text:
            continue
        new = _replace_block(text, block)
        if new != text:
            drift.append(f"{rel(root, path)}: skills table out of date")
            if not check_only:
                write(path, new)
    return drift


# ────────────────────────────────────────────────────────────────── check ──

class Report:
    def __init__(self) -> None:
        self.errors: list[str] = []
        self.warnings: list[str] = []
        self.infos: list[str] = []

    def emit(self, title: str) -> int:
        verdict = "FAIL" if self.errors else "PASS"
        parts = []
        if self.errors:
            parts.append(f"{len(self.errors)} error{'s' * (len(self.errors) != 1)}")
        if self.warnings:
            parts.append(f"{len(self.warnings)} warning{'s' * (len(self.warnings) != 1)}")
        _out(f"{title}: {verdict}" + (f" — {', '.join(parts)}" if parts else ""))
        for e in self.errors:
            _out(f"  [x] {e}")
        for w in self.warnings:
            _out(f"  [!] {w}")
        for i in self.infos:
            _out(f"  [i] {i}")
        return 1 if self.errors else 0


def _git(root: Path, *args: str, stdin: str | None = None) -> subprocess.CompletedProcess | None:
    if not shutil.which("git") or not (root / ".git").exists():
        return None
    try:
        return subprocess.run(["git", *args], cwd=root, input=stdin, capture_output=True,
                              text=True, encoding="utf-8", timeout=30)
    except (OSError, subprocess.TimeoutExpired):
        return None


def _check_ignore(root: Path, paths: list[str]) -> list[str] | None:
    """The paths git would ignore, or None without git.

    NUL-separated bytes on purpose: text-mode stdin on Windows turns "\\n" into
    "\\r\\n", git then checks `name\\r`, and `.env.*` reports `.env.example\\r` as
    ignored — a false alarm that once failed this very check.
    """
    if not shutil.which("git") or not (root / ".git").exists():
        return None
    try:
        r = subprocess.run(["git", "check-ignore", "--no-index", "-z", "--stdin"], cwd=root,
                           input="\0".join(paths).encode("utf-8") + b"\0", capture_output=True, timeout=30)
    except (OSError, subprocess.TimeoutExpired):
        return None
    return [p for p in r.stdout.decode("utf-8", "replace").split("\0") if p]


def _todo_markers(root: Path) -> list[str]:
    hits = []
    self_path = Path(__file__).resolve()
    for path in walk_files(root):
        if path.resolve() == self_path:
            continue
        if path.suffix not in TEXT_SUFFIXES and path.name not in {"Dockerfile", "Makefile"}:
            continue
        try:
            if path.stat().st_size > 512_000:
                continue
            text = path.read_text(encoding="utf-8")
        except (OSError, UnicodeDecodeError):
            continue
        for n, line in enumerate(text.splitlines(), 1):
            if TODO_MARK in line:
                hits.append(f"{rel(root, path)}:{n}")
    return hits


def _dox(root: Path, rep: Report) -> None:
    agents = root / "AGENTS.md"
    if not agents.exists():
        rep.errors.append("AGENTS.md (DOX root contract) is missing")
        return
    contracts = [p for p in walk_files(root) if p.name == "AGENTS.md" and p != agents]
    referenced: set[str] = set()
    for doc in [agents, *contracts]:
        text = doc.read_text(encoding="utf-8", errors="replace")
        # A path starts where no path character, ':' or '/' precedes it, so a URL
        # (https://host/.../AGENTS.md) never matches and never triggers a lookup.
        for m in re.finditer(r"(?<![\w.\-/:])((?:\./)?[\w.\-][\w.\-/]*/AGENTS\.md)", text):
            ref = m.group(1)
            ref = ref[2:] if ref.startswith("./") else ref
            # child refs are relative to the doc that names them, or to the root
            candidates = [doc.parent / ref, root / ref]
            hit = next((c for c in candidates if c.exists()), None)
            if hit is not None:
                referenced.add(hit.resolve().as_posix())
            elif doc == agents and "<" not in ref:
                rep.errors.append(f"AGENTS.md indexes `{ref}`, which does not exist")
    for c in contracts:
        if c.resolve().as_posix() not in referenced:
            rep.warnings.append(f"{rel(root, c)} is not listed in any parent's Child DOX Index")


def _ignore_traps(root: Path, project: dict, rep: Report) -> None:
    must_track = [p for p in project.get("required_paths", []) if (root / p).exists()]
    for base in (SKILLS_REL, ".claude/hooks", ".claude/agents", ".claude/commands", ".tmp/scripts"):
        d = root / base
        if d.is_dir():
            must_track += [rel(root, p) for p in d.rglob("*") if p.is_file()
                           and "__pycache__" not in p.parts and p.name not in OS_JUNK
                           and p.suffix not in (".pyc", ".pyo")]
    for f in (".claude/settings.json", ".harness/harness.py", ".harness/project.json", ".env.example"):
        if (root / f).exists():
            must_track.append(f)
    must_track = sorted(set(must_track))
    if not must_track:
        return
    ignored = _check_ignore(root, must_track)
    if ignored is None:
        rep.infos.append("git not available or not a repo: skipped the ignore-trap check")
        return
    for path in ignored:
        rep.errors.append(f"`{path}` is gitignored — a fresh clone, worktree or CI run would "
                          f"not get it (check for a bare `*.tmp` or a `.claude/` line)")
    if (root / ".env").exists():
        r = _git(root, "check-ignore", "--no-index", "-q", ".env")
        if r is not None and r.returncode != 0:
            rep.errors.append("`.env` exists and is NOT gitignored — secrets would be committed")


def _commandcenter(root: Path, skills: list[Skill], rep: Report) -> None:
    cfg_path = root / "config.json"
    try:
        cfg = json.loads(cfg_path.read_text(encoding="utf-8"))
    except (OSError, ValueError) as exc:
        rep.errors.append(f"config.json unreadable: {exc}")
        return
    name = cfg.get("name", "")
    if not re.match(r"^[a-z0-9][a-z0-9-]{0,48}[a-z0-9]$", name):
        rep.errors.append(f"config.json name `{name}` must match ^[a-z0-9][a-z0-9-]{{0,48}}[a-z0-9]$")
    if name.startswith("agent-"):
        rep.errors.append("config.json name must not carry the `agent-` prefix")
    if cfg.get("max_mutation_attempts") != 1:
        rep.errors.append("config.json max_mutation_attempts must be 1")
    for key in ("description", "integrations", "tags"):
        if key not in cfg:
            rep.errors.append(f"config.json is missing `{key}`")
    agents_py = root / "agents.py"
    if agents_py.exists():
        src = agents_py.read_text(encoding="utf-8")
        try:
            compile(src, str(agents_py), "exec")
        except SyntaxError as exc:
            rep.errors.append(f"agents.py does not compile: line {exc.lineno}: {exc.msg}")
        if "def build_agents" not in src:
            rep.errors.append("agents.py does not define build_agents()")
        for s in skills:
            if s.meta.get("audience") == "developer":
                continue  # builds the agent; not a runtime tool
            if (s.path / "scripts").is_dir() and any((s.path / "scripts").glob("*.py")) \
                    and f'"{s.name}"' not in src and f"'{s.name}'" not in src:
                rep.warnings.append(f"skill `{s.name}` has scripts but no tool in agents.py")


def check(root: Path, strict: bool = False) -> int:
    project = load_project(root)
    if not project:
        _out("harness check: not a scaffolded workspace (.harness/project.json missing)")
        return 2
    rep = Report()

    for p in project.get("required_paths", []):
        if not (root / p).exists():
            rep.errors.append(f"required `{p}` is missing")

    skills = discover_skills(root)
    for s in skills:
        rep.errors.extend(s.problems)
    for d in sync(root, check_only=True):
        rep.errors.append(f"{d} → run: python .harness/harness.py sync")

    _dox(root, rep)
    _ignore_traps(root, project, rep)

    if (project.get("agent") or {}).get("runtime") == "commandcenter":
        _commandcenter(root, skills, rep)

    todos = _todo_markers(root)
    if todos:
        msg = (f"{len(todos)} unfinished `{TODO_MARK}` marker(s): {', '.join(todos[:8])}"
               + (" ..." if len(todos) > 8 else ""))
        (rep.errors if strict else rep.warnings).append(msg)

    lessons = open_lessons(root, project)
    if lessons:
        rep.infos.append(f"{len(lessons)} OPEN lesson(s) in {project.get('lessons_path', 'docs/lessons.md')} "
                         "— integrate them (self-annealing skill)")
    rep.infos.append(f"{len(skills)} skill(s) in {SKILLS_REL}/")
    return rep.emit("harness check")


def open_lessons(root: Path, project: dict) -> list[str]:
    path = root / project.get("lessons_path", "docs/lessons.md")
    if not path.exists():
        return []
    text = path.read_text(encoding="utf-8")
    out = []
    for block in re.split(r"^### ", text, flags=re.M)[1:]:
        title = block.splitlines()[0].strip()
        if re.search(r"\*\*Status:\*\*\s*OPEN", block):
            out.append(title)
    return out


# ─────────────────────────────────────────────────────────────────── test ──

def test(root: Path) -> int:
    rep = Report()
    for s in discover_skills(root):
        scripts = s.path / "scripts"
        if scripts.is_dir():
            for script in sorted(scripts.glob("*.py")):
                if script.name.startswith("_"):
                    continue
                r = subprocess.run([sys.executable, str(script), "--help"], cwd=root, env=utf8_env(),
                                   capture_output=True, text=True, encoding="utf-8", errors="replace",
                                   timeout=60)
                if r.returncode != 0:
                    tail = (r.stderr or r.stdout).strip().splitlines()[-1:] or ["(no output)"]
                    rep.errors.append(f"{rel(root, script)} --help exited {r.returncode}: {tail[0]}")
        tests = s.path / "tests"
        if tests.is_dir() and any(tests.glob("test_*.py")):
            r = subprocess.run([sys.executable, "-m", "unittest", "discover", "-s", str(tests),
                                "-t", str(tests), "-p", "test_*.py"],
                               cwd=root, env=utf8_env(), capture_output=True, text=True,
                               encoding="utf-8", errors="replace", timeout=600)
            summary = (r.stderr.strip().splitlines() or ["?"])[-1]
            if r.returncode != 0:
                rep.errors.append(f"{s.name}: tests failed — {summary}")
                detail = [ln for ln in r.stderr.splitlines() if ln.startswith(("FAIL:", "ERROR:"))]
                rep.errors.extend(f"    {ln}" for ln in detail[:10])
            else:
                rep.infos.append(f"{s.name}: {summary}")
    return rep.emit("harness test")


# ────────────────────────────────────────────────────────── session-start ──

def session_start(root: Path) -> int:
    """Terse status for the SessionStart hook. Never fails a session."""
    try:
        project = load_project(root)
        if not project:
            return 0
        lines = []
        todos = _todo_markers(root)
        if todos:
            lines.append(f"- Scaffolding is unfinished: {len(todos)} `{TODO_MARK}` marker(s) "
                         f"(first: {todos[0]}). Finish them before feature work.")
        lessons = open_lessons(root, project)
        if lessons:
            lines.append(f"- {len(lessons)} OPEN lesson(s) in {project.get('lessons_path', 'docs/lessons.md')}: "
                         + "; ".join(lessons[:3]) + (" ..." if len(lessons) > 3 else ""))
        drift = sync(root, check_only=True)
        if drift:
            lines.append(f"- Skill proxies/tables drifted ({len(drift)}): run `python .harness/harness.py sync`.")
        if lines:
            _out(f"## Harness status — {project.get('name', 'this project')}\n")
            for ln in lines:
                _out(ln)
            _out("\nSession protocol: AGENTS.md § Session Protocol. End with "
                 "`python .github/skills/self-annealing/scripts/anneal.py gate`.")
    except Exception:  # noqa: BLE001 — a status hook must never block a session
        pass
    return 0


# ─────────────────────────────────────────────────────────────────── main ──

def main(argv: list[str] | None = None) -> int:
    try:  # agents read this through pipes; Windows defaults pipes to cp1252
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    except (AttributeError, ValueError):
        pass
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--root", default=str(ROOT), help="workspace root (default: this file's repo)")
    sub = ap.add_subparsers(dest="cmd", required=True)
    c = sub.add_parser("check", help="verify the harness")
    c.add_argument("--strict", action="store_true", help=f"also fail on {TODO_MARK} markers")
    sub.add_parser("sync", help="regenerate proxies and skills tables")
    sub.add_parser("test", help="run skill tests and script --help smoke")
    sub.add_parser("session-start", help="status block for the SessionStart hook")
    args = ap.parse_args(argv)
    root = Path(args.root).resolve()

    if args.cmd == "check":
        return check(root, strict=args.strict)
    if args.cmd == "sync":
        if not load_project(root):
            _out("harness sync: not a scaffolded workspace (.harness/project.json missing)")
            return 2
        changed = sync(root)
        _out(f"harness sync: {len(changed)} change(s)" if changed else "harness sync: already in sync")
        for c_ in changed:
            _out(f"  - {c_}")
        return 0
    if args.cmd == "test":
        return test(root)
    if args.cmd == "session-start":
        return session_start(root)
    return 1


if __name__ == "__main__":
    sys.exit(main())
